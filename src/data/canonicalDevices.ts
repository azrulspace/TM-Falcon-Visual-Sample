/**
 * Generates repeating 30-minute cycles for GV0032063 as seen in staging screenshots:
 * (Online 2 min, Stale 3 min, Offline 25 min, repeating every 30 minutes).
 */
function generateSpeakerConnectivityPeriods(): DeviceRecord['connectivityHistory'] {
  const periods: DeviceRecord['connectivityHistory'] = [];
  const baseTime = new Date('2026-11-12T06:59:00+08:00'); // Screenshot time Nov 12, 6:59 AM

  // Most recent period is Online (Current, 27 min)
  periods.push({
    id: 'conn-gv-0',
    record: 'Connectivity',
    status: 'online',
    from: '2026-11-12T06:59:00+08:00',
    to: null,
    durationMinutes: 27,
    recordedBy: 'Telemetry',
    recordedAt: '2026-11-12T06:59:00+08:00',
  });

  // Then repeating historical cycles for 7 days
  let cursor = new Date(baseTime.getTime() - 25 * 60 * 1000); // 6:34 AM
  let idCounter = 1;

  for (let cycle = 0; cycle < 100; cycle++) {
    // 1. Offline for 25 min
    const offFrom = new Date(cursor.getTime());
    const offTo = new Date(offFrom.getTime() + 25 * 60 * 1000);
    periods.push({
      id: `conn-gv-${idCounter++}`,
      record: 'Connectivity',
      status: 'offline',
      from: offFrom.toISOString(),
      to: offTo.toISOString(),
      durationMinutes: 25,
      recordedBy: 'Telemetry',
      recordedAt: offTo.toISOString(),
    });

    // 2. Stale for 3 min
    const staleFrom = new Date(offFrom.getTime() - 3 * 60 * 1000);
    const staleTo = new Date(offFrom.getTime());
    periods.push({
      id: `conn-gv-${idCounter++}`,
      record: 'Connectivity',
      status: 'stale',
      from: staleFrom.toISOString(),
      to: staleTo.toISOString(),
      durationMinutes: 3,
      recordedBy: 'Telemetry',
      recordedAt: staleTo.toISOString(),
    });

    // 3. Online for 2 min
    const onFrom = new Date(staleFrom.getTime() - 2 * 60 * 1000);
    const onTo = new Date(staleFrom.getTime());
    periods.push({
      id: `conn-gv-${idCounter++}`,
      record: 'Connectivity',
      status: 'online',
      from: onFrom.toISOString(),
      to: onTo.toISOString(),
      durationMinutes: 2,
      recordedBy: 'Telemetry',
      recordedAt: onTo.toISOString(),
    });

    cursor = new Date(onFrom.getTime() - 25 * 60 * 1000);
  }

  return periods;
}

