/**
 * Returns metric definitions filtered to an array of metric IDs,
 * or all metrics if metricIds is omitted.
 */
export function getMetricDefinitions(metricIds?: string[]): MetricDefinition[] {
  if (!metricIds || metricIds.length === 0) {
    return Object.values(METRIC_DEFINITIONS);
  }
  return metricIds
    .map((id) => METRIC_DEFINITIONS[id])
    .filter((def): def is MetricDefinition => Boolean(def));
}

export const METRIC_DEFINITIONS_LIST: MetricDefinition[] = Object.values(METRIC_DEFINITIONS);

export function getMetricById(id: string): MetricDefinition | undefined {
  return METRIC_DEFINITIONS[id];
}

export function getMetricsForReport(reportId: string): MetricDefinition[] {
  const report = REPORT_TEMPLATES.find((r) => r.id === reportId);
  if (!report) return [];
  return getMetricDefinitions(report.metricIds);
}
